const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('vnx',{
  systemStatus:()=>ipcRenderer.invoke('system:status'),
  getState:()=>ipcRenderer.invoke('state:get'),
  activateLicense:(payload)=>ipcRenderer.invoke('license:activate',payload),
  refreshLicense:()=>ipcRenderer.invoke('license:status'),
  chooseFolder:()=>ipcRenderer.invoke('folder:choose'),
  revokeFolder:(folder)=>ipcRenderer.invoke('folder:revoke',folder),
  listFolder:(folder)=>ipcRenderer.invoke('folder:list',folder),
  createTestFile:(folder)=>ipcRenderer.invoke('folder:create-test',folder),
  scanCommonData:()=>ipcRenderer.invoke('discovery:scan-common'),
  chooseAndScanData:()=>ipcRenderer.invoke('discovery:choose-scan'),
  authorizeDiscoveredFolder:(folder)=>ipcRenderer.invoke('discovery:authorize',folder),
  listPortals:()=>ipcRenderer.invoke('portal:list'),
  savePortal:(payload)=>ipcRenderer.invoke('portal:save',payload),
  connectPortal:(id)=>ipcRenderer.invoke('portal:connect',id),
  checkPortal:(id)=>ipcRenderer.invoke('portal:check',id),
  calibratePortal:(id)=>ipcRenderer.invoke('portal:calibrate',id),
  getPortalProfile:(id)=>ipcRenderer.invoke('portal:profile',id),
  adaptivePortalQuery:(id,question)=>ipcRenderer.invoke('portal:adaptive-query',id,question),
  verifiedProductCount:(question,scope)=>ipcRenderer.invoke('portal:verified-product-count',{question,scope}),
  removePortal:(id)=>ipcRenderer.invoke('portal:remove',id),
  exportData:(payload)=>ipcRenderer.invoke('export:data',payload),
  connectShopify:(payload)=>ipcRenderer.invoke('shopify:connect',payload),
  shopifyStatus:()=>ipcRenderer.invoke('shopify:status'),
  disconnectShopify:()=>ipcRenderer.invoke('shopify:disconnect'),
  connectIntegration:(payload)=>ipcRenderer.invoke('integration:connect',payload),
  integrationStatus:(module)=>ipcRenderer.invoke('integration:status',module),
  disconnectIntegration:(module)=>ipcRenderer.invoke('integration:disconnect',module),
  startOAuth:(payload)=>ipcRenderer.invoke('oauth:start',payload),
  pollOAuth:(payload)=>ipcRenderer.invoke('oauth:status',payload),
  openExternal:(url)=>ipcRenderer.invoke('app:open-external',url),
  openQuickAssist:()=>ipcRenderer.invoke('support:quick-assist'),
  stopSupport:()=>ipcRenderer.invoke('support:stop'),
  sendChat:(messages,scope)=>ipcRenderer.invoke('chat:send',{messages,scope}),
  pairDemo:()=>ipcRenderer.invoke('device:pair-demo')
});
